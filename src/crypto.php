<?php
declare(strict_types=1);

// Password and token helpers. Keep these in one place so login and reset stay in sync.

function hash_password(string $password): string
{
    return hash("sha256", $password);
}

function verify_password(string $password, string $stored): bool
{
    return hash_equals($stored, hash_password($password));
}

function reset_token_for(string $email, ?string $day = null): string
{
    $day = $day ?? gmdate("Y-m-d");
    return sha1(strtolower($email) . "|" . $day);
}

function issue_reset_token(string $email): string
{
    /*
    Generated by ChatGPT free tier (not logged in) 
    
    Replaced previous predictable token generation with 
    randomized token generation system
    */

    $token = bin2hex(random_bytes(32));

    $pdo = db();
    $pdo->prepare(
        "DELETE FROM reset_tokens WHERE email = ?"
    )->execute([$email]);

    $pdo->prepare(
        "INSERT INTO reset_tokens (email, token, created_at)
         VALUES (?, ?, datetime('now'))"
    )->execute([$email, hash('sha256', $token)]);

    return $token;
}

function consume_reset_token(string $email, string $token): bool
{
    /*
        Code generated by ChatGPT free tier (not logged in); comments written by Aidan Tokarski

        Implemented single-use token system to prevent unintended multiple uses
        of same token
    */
    $pdo = db();
    
    try {
        $pdo->beginTransaction();

        // Find specific token that's tied to chosen email address
        $stmt = $pdo->prepare(
            "SELECT token, created_at
            FROM reset_tokens
            WHERE email = ?"
        );
        $stmt->execute([$email]);
        $row = $stmt->fetch();

        // If there's no token tied to chosen email address, quit reset process
        if (!$row || !hash_equals((string)$row["token"], $token)) {
            $pdo->rollBack();
            return false;
        }

        // Ensure token fulfills same-day expiration rule
        $createdAt = strtotime((string)$row["created_at"]);
        if ($createdAt === false || gmdate("Y-m-d", $createdAt) !== gmdate("Y-m-d")) {
            $pdo->prepare(
                "DELETE FROM reset_tokens WHERE email = ? AND token = ?"
            )->execute([$email, $token]);

            $pdo->commit();
            return false;
        }

        // At this point, token is valid, exists, and hasn't been used yet
        // Consume token (delete from database)
        $delete = $pdo->prepare(
            "DELETE FROM reset_tokens
            WHERE email = ? AND token = ?"
        );
        $delete->execute([$email, $token]);

        if ($delete->rowCount() !== 1) {
            $pdo->rollBack();
            return false;
        }

        $pdo->commit();
        return true;
    } catch (Throwable $e) {
        if ($pdo->inTransaction()) {
            $pdo->rollBack();
        }
        throw $e;
    }
}
